/* ============================================================================
   第二套词典：以「中文原文」为键
   ----------------------------------------------------------------------------
   页面文案大多写在渲染函数拼出来的 HTML 里，逐条给语义 key 维护成本太高。
   这里直接用中文原文当键，配合 localizeDom() 在 DOM 层替换：

     I18N_SRC.en['已刷新'] = 'Refreshed'
     TT('已刷新')                     → 直接取译文（toast、弹窗用）
     localizeDom(el)                  → 把 el 里的中文文本节点换成译文

   动态句子可以用 {} 占位：
     '扫描完成：{} 个模组': 'Scan complete: {} mods'
   ========================================================================== */
const I18N_SRC = { en: {}, fr: {}, de: {}, sv: {} };

let I18N_LANG = 'zh';

function i18nLang() {
  return I18N_LANG;
}

const I18N_ATTRS = ['title', 'placeholder', 'alt'];
const I18N_CJK = /[\u4e00-\u9fff]/;

/* 把带 {} 的键编译成正则（惰性缓存） */
const _srcRe = new WeakMap();
function srcPatterns(dict) {
  let list = _srcRe.get(dict);
  if (list) return list;
  list = [];
  Object.keys(dict).forEach(k => {
    if (k.indexOf('{}') < 0) return;
    const body = k.split('{}').map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('(.+?)');
    try { list.push({ re: new RegExp('^' + body + '$'), out: dict[k] }); } catch (e) {}
  });
  list.sort((a, b) => b.re.source.length - a.re.source.length);
  _srcRe.set(dict, list);
  return list;
}

/** 查表用的键：连续空白压成一个空格（HTML 里换行缩进不等于内容差异） */
function i18nKey(s) {
  return String(s).replace(/\s+/g, ' ').trim();
}

/** 单条文本翻译：精确命中 → {} 模式 → 原样返回 */
function TT(s, vars) {
  let out = s;
  if (I18N_LANG !== 'zh' && s) {
    const dict = I18N_SRC[I18N_LANG];
    const key = i18nKey(s);
    if (dict) {
      if (Object.prototype.hasOwnProperty.call(dict, key)) {
        out = dict[key];
      } else {
        const pats = srcPatterns(dict);
        for (let i = 0; i < pats.length; i++) {
          const m = pats[i].re.exec(key);
          if (m) {
            let n = 0;
            out = String(pats[i].out).replace(/\{\}/g, () => m[++n] || '');
            break;
          }
        }
      }
    }
  }
  if (vars && typeof vars === 'object') {
    out = String(out).replace(/\{(\w+)\}/g, (m, k) =>
      (vars[k] === undefined ? m : String(vars[k])));
  }
  return out;
}

function localizeTextNode(node) {
  const raw = node.nodeValue;
  if (!raw || !I18N_CJK.test(raw)) return;
  const key = i18nKey(raw);
  if (!key) return;
  const tv = TT(key);
  if (tv !== key) node.nodeValue = tv;
}

function localizeAttrs(el) {
  if (!el || el.nodeType !== 1) return;
  for (let i = 0; i < I18N_ATTRS.length; i++) {
    const a = I18N_ATTRS[i];
    const v = el.getAttribute(a);
    if (!v || !I18N_CJK.test(v)) continue;
    const tv = TT(v);
    if (tv !== v) el.setAttribute(a, tv);
  }
}

/** 把某棵子树里的中文换成当前语言（zh 下直接跳过） */
function localizeDom(root) {
  if (I18N_LANG === 'zh' || !root) return;
  if (root.nodeType === 3) { localizeTextNode(root); return; }
  if (root.nodeType === 1) {
    localizeAttrs(root);
    localizeBlocks(root);
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (let i = 0; i < nodes.length; i++) localizeTextNode(nodes[i]);
  if (root.querySelectorAll) {
    const els = root.querySelectorAll('[title],[placeholder],[alt]');
    for (let i = 0; i < els.length; i++) localizeAttrs(els[i]);
  }
}

/* 有些句子被 <b>/<code> 切成了好几段，逐段翻译会语序错乱。
   这里先在「文本容器」这一层整段查一遍：命中就整段替换（译文可自带 <b> 等标签）。
   只在子元素全是这些纯样式标签时动手，避免把 <sup id>、<input>、<img> 之类干掉。 */
const BLOCKISH = 'div,p,li,td,th,tr,ul,ol,table,section,header,footer,h1,h2,h3,h4,h5,h6,button,a';
const INLINE_OK = { B: 1, STRONG: 1, I: 1, EM: 1, CODE: 1 };

function blockSafe(el) {
  if (el.querySelector(BLOCKISH)) return false;
  const kids = el.children;
  for (let i = 0; i < kids.length; i++) {
    const k = kids[i];
    if (!INLINE_OK[k.tagName]) return false;
    if (k.children.length) return false;
  }
  return true;
}

function localizeBlocks(root) {
  const els = root.querySelectorAll('*');
  for (let i = 0; i < els.length; i++) {
    const el = els[i];
    if (el._i18nBlock) continue;
    if (!el.children.length) continue;
    if (!blockSafe(el)) continue;
    const txt = (el.textContent || '').trim();
    if (!txt || !I18N_CJK.test(txt)) continue;
    const tv = TT(txt);
    if (tv !== txt) {
      el.innerHTML = tv;
      el._i18nBlock = 1;
      localizeAttrs(el);
    }
  }
}

/* 动态渲染的内容（异步填充、toast、右键菜单）也要跟着翻译，
   所以挂一个 MutationObserver：新增节点 / 改文本 / 改 title 都兜住。 */
let _i18nObserver = null;

function enableDomI18n(on) {
  if (_i18nObserver) { _i18nObserver.disconnect(); _i18nObserver = null; }
  if (!on || !document.body) return;
  _i18nObserver = new MutationObserver(muts => {
    for (let i = 0; i < muts.length; i++) {
      const m = muts[i];
      if (m.type === 'attributes') { localizeAttrs(m.target); continue; }
      const added = m.addedNodes;
      for (let j = 0; j < added.length; j++) {
        const nd = added[j];
        if (nd.nodeType === 1 || nd.nodeType === 3) localizeDom(nd);
      }
    }
  });
  _i18nObserver.observe(document.body, {
    childList: true, subtree: true,
    attributes: true, attributeFilter: I18N_ATTRS,
  });
  localizeDom(document.body);
}

function T(key, vars) {
  const dict = I18N_DICT[I18N_LANG] || {};
  let s = dict[key];
  if (s === undefined) s = I18N_DICT.zh[key];   // 回退中文
  if (s === undefined) return key;              // 再回退 key
  if (vars && typeof vars === 'object') {
    s = String(s).replace(/\{(\w+)\}/g, (m, k) =>
      (vars[k] === undefined ? m : String(vars[k])));
  }
  return s;
}

/** 切换语言：只改内存状态，持久化由调用方负责 */
function setLang(code) {
  if (!I18N_DICT[code]) return false;
  I18N_LANG = code;
  document.documentElement.lang =
    ({ zh: 'zh-CN', en: 'en', fr: 'fr', de: 'de', sv: 'sv' })[code] || 'zh-CN';
  document.title = T('brand.name');
  enableDomI18n(code !== 'zh');
  return true;
}

/** 刷新所有带 data-i18n* 属性的静态节点（导航、顶部栏这些） */
function applyI18nDom(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = T(el.dataset.i18n);
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = T(el.dataset.i18nTitle);
  });
  scope.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = T(el.dataset.i18nPh);
  });
}

